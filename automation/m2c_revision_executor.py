def verify_m2c_revision_pin(pin: M2CRevisionPin, *, archive: ContentAddressedArchive) -> None:
    """Read-only current-pin artifact preflight for callers without a run binding."""

    if not isinstance(pin, M2CRevisionPin):
        raise M2CExecutorInputError("m2c revision pin must be typed")
    if not pin.available or pin.source_artifact is None or pin.tool_artifact is None:
        raise M2CExecutorUnavailable("pinned m2c source or tool is unavailable", code="m2c_pinned_artifact_unavailable")
    _archive_bytes(
        archive,
        pin.source_artifact,
        "pinned source artifact",
        prefix=_SOURCE_PREFIX,
        maximum=_MAX_TOOL_BYTES,
        reject_nul=False,
    )
    _archive_bytes(
        archive,
        pin.tool_artifact,
        "pinned tool artifact",
        prefix=_TOOL_PREFIX,
        maximum=_MAX_TOOL_BYTES,
        reject_nul=False,
    )


