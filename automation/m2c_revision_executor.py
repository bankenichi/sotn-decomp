"""Trusted archive-backed execution for the pinned m2c decompiler.

The historical m2c provider accepts a caller callback.  That is useful for
unit tests, but it is not a production boundary: a callback can inspect the
checkout, choose a different command, or return a fabricated source file.  The
executor in this module consumes one immutable :class:`M2CRevisionPin`, one
typed :class:`M2CInvocation`, and only bytes verified by the run archive.

Every external m2c call is preceded by a durable request document.  Completed
requests are replayed from their immutable result document, while a request
with no result is returned as a typed pending handoff.  Reconstruction only
verifies archive objects and identities.  It never invokes m2c and never writes
the archive.
"""

