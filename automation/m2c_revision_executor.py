class M2CExecutorError(ValueError):
    """Base class for immutable binding and execution failures."""

    code = "m2c_executor_error"
    status = "invalid"

    def __init__(self, detail: str, *, code: Optional[str] = None) -> None:
        super().__init__(detail)
        if code:
            self.code = code
        self.detail = detail


class M2CExecutorInputError(M2CExecutorError):
    """A serialized binding or invocation is malformed or forged."""

    code = "m2c_executor_input_invalid"


class M2CExecutorUnavailable(M2CExecutorError):
    """The trusted pinned runner cannot execute on this platform."""

    code = "m2c_executor_unavailable"
    status = "unavailable"


class M2CExecutorRefused(M2CExecutorError):
    """The pinned m2c runner rejected a bounded invocation."""

    code = "m2c_executor_refused"
    status = "refused"


class M2CExecutorTimeout(M2CExecutorError):
    """The pinned runner exceeded the immutable wall-clock bound."""

    code = "m2c_executor_timeout"
    status = "timeout"


class M2CExecutorInvalidResponse(M2CExecutorError):
    """The pinned runner returned malformed or over-sized output."""

    code = "m2c_executor_invalid_response"
    status = "invalid"


class M2CExecutorInapplicable(M2CExecutorError):
    """The real pinned tool has no backend for the requested platform."""

    code = "m2c_target_inapplicable"
    status = "inapplicable"


class M2CExecutorPending(M2CExecutorError):
    """A durable request exists without a terminal result."""

    code = "m2c_request_pending"
    status = "pending"


def _strict_mapping(value: Any, fields: Sequence[str], label: str) -> dict[str, Any]:
    if not isinstance(value, Mapping):
        raise M2CExecutorInputError(f"{label} must be an object")
    data = dict(value)
    if any(not isinstance(key, str) for key in data):
        raise M2CExecutorInputError(f"{label} keys must be text")
    required = set(fields)
    missing = required.difference(data)
    unknown = set(data).difference(required)
    if missing:
        raise M2CExecutorInputError(
            f"{label} is missing fields: {', '.join(sorted(missing))}"
        )
    if unknown:
        raise M2CExecutorInputError(
            f"{label} has unknown fields: {', '.join(sorted(unknown))}"
        )
    return data


def _identity(value: Any, label: str) -> str:
    try:
        return validate_hash(value, label)
    except Exception as exc:
        raise M2CExecutorInputError(f"{label} must be a sha256 identity") from exc


def _artifact(value: Any, label: str) -> ArtifactRef:
    try:
        item = value if isinstance(value, ArtifactRef) else ArtifactRef.from_dict(value)
    except Exception as exc:
        raise M2CExecutorInputError(f"{label} is not an ArtifactRef") from exc
    if "\\" in item.path:
        raise M2CExecutorInputError(f"{label} must use POSIX separators")
    try:
        validate_relative_path(item.path, label)
    except Exception as exc:
        raise M2CExecutorInputError(f"{label} is not a safe relative path") from exc
    return item


def _artifact_identity(value: Optional[ArtifactRef]) -> Optional[dict[str, Any]]:
    return None if value is None else value.to_dict()


def _bounded_bytes(
    value: Any,
    label: str,
    maximum: int,
    *,
    allow_empty: bool = False,
    reject_nul: bool = True,
) -> bytes:
    if not isinstance(value, bytes):
        raise M2CExecutorInputError(f"{label} must be bytes")
    if not allow_empty and not value:
        raise M2CExecutorInputError(f"{label} must be nonempty")
    if len(value) > maximum:
        raise M2CExecutorInputError(f"{label} exceeds its immutable bound")
    if reject_nul and b"\x00" in value:
        raise M2CExecutorInputError(f"{label} contains NUL bytes")
    return value


def _archive_bytes(
    archive: ContentAddressedArchive,
    reference: ArtifactRef,
    label: str,
    *,
    prefix: str,
    maximum: int,
    allow_empty: bool = False,
    reject_nul: bool = True,
) -> bytes:
    reference = _artifact(reference, label)
    if not reference.path.startswith(prefix):
        raise M2CExecutorInputError(f"{label} is outside its pinned archive prefix")
    try:
        data = archive.verify(reference)
    except (ArchiveError, OSError, TypeError, ValueError) as exc:
        raise M2CExecutorInputError(f"{label} is missing or corrupt") from exc
    return _bounded_bytes(
        data,
        label,
        maximum,
        allow_empty=allow_empty,
        reject_nul=reject_nul,
    )


def _platform() -> str:
    return _PLATFORM_WSL if _is_windows_host() else _PLATFORM_POSIX


def _is_windows_host() -> bool:
    """Return the host mode without mutating ``os.name`` in callers/tests."""

    return os.name == "nt"


def _target_for(platform: str) -> Optional[str]:
    try:
        return M2C_TARGET_MAP[platform]
    except KeyError as exc:
        raise M2CExecutorInputError("m2c platform is unsupported") from exc


def _recipient_parts(recipient_id: str) -> tuple[str, str]:
    if not isinstance(recipient_id, str):
        raise M2CExecutorInputError("m2c recipient id must be text")
    pieces = recipient_id.split(":")
    if len(pieces) != 3 or not all(pieces):
        raise M2CExecutorInputError("m2c recipient id must be platform:segment:function")
    platform, _segment, function_name = pieces
    if platform not in _SUPPORTED_PLATFORMS:
        raise M2CExecutorInputError("m2c recipient platform is unsupported")
    if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", function_name) is None:
        raise M2CExecutorInputError("m2c recipient function is not a C identifier")
    return platform, function_name


def _safe_switches(value: Any) -> tuple[str, ...]:
    if not isinstance(value, (tuple, list)):
        raise M2CExecutorInputError("m2c switches must be a sequence")
    switches = tuple(value)
    if len(switches) > _MAX_SWITCHES:
        raise M2CExecutorInputError("m2c switch count exceeds its bound")
    seen: set[str] = set()
    for switch in switches:
        if not isinstance(switch, str) or switch not in _ALLOWED_SWITCHES:
            raise M2CExecutorInputError("m2c invocation contains an unapproved switch")
        if switch in seen:
            raise M2CExecutorInputError("m2c switches must not repeat")
        seen.add(switch)
        if any(char in switch for char in ("\x00", "/", "\\", "..")):
            raise M2CExecutorInputError("m2c switch contains path or NUL data")
    return switches


def _current_runtime_identity(platform: str) -> str:
    interpreter = "python3" if platform == _PLATFORM_WSL else "sys.executable"
    if platform == _PLATFORM_WSL:
        interpreter_identity = hash_canonical({"executable": "python3"})
    else:
        try:
            executable = str(Path(sys.executable).resolve(strict=False))
        except (OSError, RuntimeError):
            executable = sys.executable
        interpreter_identity = hash_bytes(executable.encode("utf-8"))
    return hash_canonical(
        {
            "protocol": M2C_RUNTIME_PROTOCOL,
            "platform": platform,
            "interpreter": interpreter,
            "interpreter_identity": interpreter_identity,
            "implementation": sys.implementation.name,
            "python_major": sys.version_info.major,
            "python_minor": sys.version_info.minor,
            "no_user_site": True,
            "no_bytecode": True,
        }
    )


def _pin_dict(pin: M2CRevisionPin) -> dict[str, Any]:
    return {**pin.identity_payload(), "pin_identity": pin.pin_identity}


_PIN_FIELDS = (
    "protocol",
    "revision",
    "source_artifact",
    "tool_artifact",
    "runner_identity",
    "available",
    "unavailable_reason",
    "pin_identity",
)


def _pin_from_dict(
    value: Any,
    *,
    archive: ContentAddressedArchive,
) -> M2CRevisionPin:
    data = _strict_mapping(value, _PIN_FIELDS, "m2c revision pin")
    if data["protocol"] != M2C_PIN_PROTOCOL:
        raise M2CExecutorInputError("m2c revision pin protocol differs")
    try:
        revision = M2CRevisionIdentity.from_dict(data["revision"])
        source = None if data["source_artifact"] is None else _artifact(data["source_artifact"], "pin source")
        tool = None if data["tool_artifact"] is None else _artifact(data["tool_artifact"], "pin tool")
        pin = M2CRevisionPin(
            revision=revision,
            source_artifact=source,
            tool_artifact=tool,
            runner_identity=data["runner_identity"],
            available=data["available"],
            unavailable_reason=data["unavailable_reason"],
        )
    except (M2CProviderError, TypeError, ValueError) as exc:
        raise M2CExecutorInputError("m2c revision pin is malformed") from exc
    if data["pin_identity"] != pin.pin_identity:
        raise M2CExecutorInputError("m2c revision pin identity changed")
    if pin.available:
        assert pin.source_artifact is not None and pin.tool_artifact is not None
        _archive_bytes(
            archive,
            pin.source_artifact,
            "pinned source artifact",
            prefix=_SOURCE_PREFIX,
            maximum=_MAX_TOOL_BYTES,
            reject_nul=False,
        )
        _archive_bytes(
            archive,
            pin.tool_artifact,
            "pinned tool artifact",
            prefix=_TOOL_PREFIX,
            maximum=_MAX_TOOL_BYTES,
            reject_nul=False,
        )
    return pin


@dataclass(frozen=True)
class M2CExecutorPreflight:
    status: str
    code: str
    platform: str
    revision_id: str
    pin_identity: str
    runner_identity: str
    target: Optional[str]
    target_map: Mapping[str, Optional[str]]
    runtime_identity: str
    detail: str = ""

    def __post_init__(self) -> None:
        if self.status not in {"ready", "unavailable", "refused", "inapplicable"}:
            raise M2CExecutorInputError("m2c preflight status is invalid")
        if not isinstance(self.code, str) or not self.code:
            raise M2CExecutorInputError("m2c preflight code is required")
        if self.platform not in _SUPPORTED_PLATFORMS | {_PLATFORM_POSIX, _PLATFORM_WSL}:
            raise M2CExecutorInputError("m2c preflight platform is invalid")
        if len(self.revision_id) != 40 or any(char not in "0123456789abcdef" for char in self.revision_id):
            raise M2CExecutorInputError("m2c preflight revision is invalid")
        _identity(self.pin_identity, "m2c preflight pin identity")
        _identity(self.runner_identity, "m2c preflight runner identity")
        _identity(self.runtime_identity, "m2c preflight runtime identity")
        if not isinstance(self.target_map, Mapping) or dict(self.target_map) != dict(M2C_TARGET_MAP):
            raise M2CExecutorInputError("m2c preflight target map is not exact")
        if not isinstance(self.detail, str):
            raise M2CExecutorInputError("m2c preflight detail must be text")

    @property
    def ready(self) -> bool:
        return self.status == "ready"

    def to_dict(self) -> dict[str, Any]:
        return {
            "protocol": M2C_PREFLIGHT_PROTOCOL,
            "status": self.status,
            "code": self.code,
            "platform": self.platform,
            "revision_id": self.revision_id,
            "pin_identity": self.pin_identity,
            "runner_identity": self.runner_identity,
            "target": self.target,
            "target_map": dict(self.target_map),
            "runtime_identity": self.runtime_identity,
            "detail": self.detail,
        }


@dataclass(frozen=True)
class M2CExecutionResult:
    status: str
    request_id: str
    invocation_id: str
    revision_id: str
    platform: str
    target: Optional[str]
    reason_code: str
    detail: str
    returncode: Optional[int] = None
    source_artifact: Optional[ArtifactRef] = None
    output_artifact: Optional[ArtifactRef] = None
    result_identity: str = ""

    def __post_init__(self) -> None:
        if self.status not in {"success", "unavailable", "refused", "timeout", "invalid", "inapplicable"}:
            raise M2CExecutorInputError("m2c result status is invalid")
        _identity(self.request_id, "m2c result request id")
        _identity(self.invocation_id, "m2c result invocation id")
        if len(self.revision_id) != 40 or any(char not in "0123456789abcdef" for char in self.revision_id):
            raise M2CExecutorInputError("m2c result revision is invalid")
        if self.platform not in _SUPPORTED_PLATFORMS:
            raise M2CExecutorInputError("m2c result platform is invalid")
        expected_target = _target_for(self.platform)
        if self.target != expected_target:
            raise M2CExecutorInputError("m2c result target map differs")
        if not isinstance(self.reason_code, str) or not self.reason_code:
            raise M2CExecutorInputError("m2c result reason code is required")
        if not isinstance(self.detail, str) or not self.detail:
            raise M2CExecutorInputError("m2c result detail is required")
        if self.returncode is not None and (
            isinstance(self.returncode, bool) or not isinstance(self.returncode, int)
        ):
            raise M2CExecutorInputError("m2c result return code is invalid")
        if self.source_artifact is not None:
            object.__setattr__(self, "source_artifact", _artifact(self.source_artifact, "m2c result source"))
        if self.output_artifact is not None:
            object.__setattr__(self, "output_artifact", _artifact(self.output_artifact, "m2c result output"))
        if self.status == "success" and self.source_artifact is None:
            raise M2CExecutorInputError("successful m2c result has no source artifact")
        if self.status != "success" and self.source_artifact is not None:
            raise M2CExecutorInputError("non-success m2c result has a source artifact")
        expected = hash_canonical(self.identity_payload())
        if self.result_identity and self.result_identity != expected:
            raise M2CExecutorInputError("m2c result identity changed")
        object.__setattr__(self, "result_identity", expected)

    def identity_payload(self) -> dict[str, Any]:
        return {
            "protocol": M2C_RESULT_PROTOCOL,
            "status": self.status,
            "request_id": self.request_id,
            "invocation_id": self.invocation_id,
            "revision_id": self.revision_id,
            "platform": self.platform,
            "target": self.target,
            "reason_code": self.reason_code,
            "detail": self.detail,
            "returncode": self.returncode,
            "source_artifact": _artifact_identity(self.source_artifact),
            "output_artifact": _artifact_identity(self.output_artifact),
        }

    def to_dict(self) -> dict[str, Any]:
        return {**self.identity_payload(), "result_identity": self.result_identity}

    @classmethod
    def from_dict(cls, value: Mapping[str, Any]) -> "M2CExecutionResult":
        fields = (
            "protocol",
            "status",
            "request_id",
            "invocation_id",
            "revision_id",
            "platform",
            "target",
            "reason_code",
            "detail",
            "returncode",
            "source_artifact",
            "output_artifact",
            "result_identity",
        )
        data = _strict_mapping(value, fields, "m2c result")
        if data["protocol"] != M2C_RESULT_PROTOCOL:
            raise M2CExecutorInputError("m2c result protocol differs")
        return cls(
            status=data["status"],
            request_id=data["request_id"],
            invocation_id=data["invocation_id"],
            revision_id=data["revision_id"],
            platform=data["platform"],
            target=data["target"],
            reason_code=data["reason_code"],
            detail=data["detail"],
            returncode=data["returncode"],
            source_artifact=(None if data["source_artifact"] is None else _artifact(data["source_artifact"], "m2c result source")),
            output_artifact=(None if data["output_artifact"] is None else _artifact(data["output_artifact"], "m2c result output")),
            result_identity=data["result_identity"],
        )


